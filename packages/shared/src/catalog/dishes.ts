import type { Unit } from '../domain/units';
import type { CatalogIngredientId } from './ingredients';

/** Familles de plats du catalogue (libellés traduits côté mobile). */
export const DISH_PACKS = ['senegalese', 'pasta', 'couscous'] as const;
export type DishPack = (typeof DISH_PACKS)[number];

export interface DishTemplateIngredient {
  ingredient: CatalogIngredientId;
  /** Nul = « au goût ». */
  quantity: number | null;
  unit: Unit | null;
}

export interface DishTemplate {
  id: string;
  name: string;
  aliases?: readonly string[];
  pack: DishPack;
  /** Nombre de portions pour lequel les quantités sont prévues. */
  servings: number;
  ingredients: readonly DishTemplateIngredient[];
}

/** Raccourci d'écriture : [ingrédient, quantité, unité]. */
type Row = readonly [CatalogIngredientId, number | null, Unit | null];
const rows = (list: readonly Row[]): DishTemplateIngredient[] =>
  list.map(([ingredient, quantity, unit]) => ({ ingredient, quantity, unit }));

